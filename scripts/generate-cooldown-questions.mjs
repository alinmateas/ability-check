#!/usr/bin/env node
/**
 * Fetches League of Legends ability data for the full champion roster from
 * Riot's Data Dragon CDN and generates multiple-choice quiz questions about
 * ability cooldowns (Q/W/E/R only — Data Dragon doesn't expose passive
 * cooldowns).
 *
 * Usage:
 *   node scripts/generate-cooldown-questions.mjs
 *
 * Requires Node 18+ (built-in fetch). Writes data/questions.generated.ts.
 */

import { writeFile } from "node:fs/promises";
import path from "node:path";

const PATCH = "16.17.1";
const BASE = `https://ddragon.leagueoflegends.com/cdn/${PATCH}/data/en_US`;
const OUTPUT_PATH = path.resolve("data/questions.generated.ts");

const SLOTS = ["Q", "W", "E", "R"];

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: ${res.status} ${res.statusText}`);
  }
  return res.json();
}

/** Formats a cooldown number the same way the hand-written questions do, e.g. 20 -> "20s", 1.5 -> "1.5s". */
function formatCooldown(value) {
  const rounded = Math.round(value * 100) / 100;
  return `${rounded}s`;
}

/** Picks 3 wrong-answer cooldown values, reusing other ranks' real values first and padding with synthetic ones if needed. */
function buildDistractors(cooldowns, correctIndex) {
  const correct = cooldowns[correctIndex];
  const pool = new Set(
    cooldowns.filter((value, i) => i !== correctIndex && value !== correct)
  );

  let offset = 2;
  while (pool.size < 3 && offset < 40) {
    const up = correct + offset;
    const down = correct - offset;
    if (down > 0 && down !== correct) pool.add(down);
    if (pool.size < 3 && up !== correct) pool.add(up);
    offset += 2;
  }

  return [...pool].slice(0, 3);
}

function buildQuestion(champion, championId, spell, slot, rank, difficulty) {
  const cooldowns = spell.cooldown;
  const rankIndex = rank - 1;
  const correct = cooldowns[rankIndex];
  const distractors = buildDistractors(cooldowns, rankIndex);
  const choices = [correct, ...distractors]
    .sort((a, b) => a - b)
    .map(formatCooldown);

  return {
    id: `${championId.toLowerCase()}-${slot.toLowerCase()}-cooldown-rank${rank}`,
    type: "multiple-choice",
    champion,
    championId,
    category: "abilities",
    difficulty,
    ability: `${spell.name} (${slot})`,
    text: `What is ${spell.name}'s cooldown at rank ${rank}?`,
    choices,
    answer: formatCooldown(correct),
  };
}

function questionsForSpell(champion, championId, spell, slot) {
  const cooldowns = spell.cooldown ?? [];
  const hasRealCooldown = cooldowns.some((value) => value > 0);
  if (!hasRealCooldown) return [];

  const maxRank = cooldowns.length;
  const questions = [buildQuestion(champion, championId, spell, slot, 1, "easy")];

  // Add a second, harder question about the max-rank cooldown when it
  // actually differs from rank 1 (e.g. ultimates capped at rank 3).
  if (maxRank > 1 && cooldowns[maxRank - 1] !== cooldowns[0]) {
    questions.push(
      buildQuestion(champion, championId, spell, slot, maxRank, "hard")
    );
  }

  return questions;
}

async function main() {
  console.log(`Fetching champion list for patch ${PATCH}...`);
  const championList = await fetchJson(`${BASE}/champion.json`);

  const championIds = Object.values(championList.data)
    .map((c) => c.id)
    .sort();

  console.log(`Found ${championIds.length} champions: ${championIds.join(", ")}`);

  const CONCURRENCY = 10;
  const allQuestions = [];
  let completed = 0;

  async function processChampion(championId) {
    const detail = await fetchJson(`${BASE}/champion/${championId}.json`);
    const data = detail.data[championId];
    const champion = data.name;

    const questions = [];
    data.spells.forEach((spell, i) => {
      const slot = SLOTS[i];
      questions.push(...questionsForSpell(champion, championId, spell, slot));
    });

    completed += 1;
    console.log(`(${completed}/${championIds.length}) ${championId} — ${questions.length} questions`);
    return questions;
  }

  // Simple fixed-size worker pool so we don't fire ~170 requests at once.
  const queue = [...championIds];
  async function worker() {
    while (queue.length > 0) {
      const championId = queue.shift();
      const questions = await processChampion(championId);
      allQuestions.push(...questions);
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  const fileContents = `// AUTO-GENERATED by scripts/generate-cooldown-questions.mjs — do not edit by hand.
// Source: Data Dragon patch ${PATCH}. Re-run the script to regenerate after a balance patch.
import { Question } from "@/lib/quiz-types";

export const generatedAbilityQuestions: Question[] = ${JSON.stringify(
    allQuestions,
    null,
    2
  )};
`;

  await writeFile(OUTPUT_PATH, fileContents, "utf8");
  console.log(`\nWrote ${allQuestions.length} questions to ${OUTPUT_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
